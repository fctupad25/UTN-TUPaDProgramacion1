# 2) Desarrolla un programa que solicite al usuario un número entero y determine la cantidad de
# dígitos que contiene.

num= str(int(input("Introduce un número entero: ")))            # Solicita al usuario un numero

digitos = len(num)                                              # Evalua la longitud del numero ingresado

print(f"La cantidad de digitos del número ingresado es de {digitos}.")



